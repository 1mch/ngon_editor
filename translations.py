def tr(key, **kwargs):
    text = TEXTS.get(CURRENT_LANG, {}).get(key, key)
    if kwargs:
        return text.format(**kwargs)
    return text

def set_language(lang_code):
    global CURRENT_LANG
    if lang_code in TEXTS:
        CURRENT_LANG = lang_code
